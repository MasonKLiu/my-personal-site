import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { NextIntlClientProvider } from "next-intl";
import { notFound } from "next/navigation";
import "../globals.css"; // 注意：因為移入了 [locale]，路徑要多退一層

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "我的個人網頁",
  description: "Generated by create next app",
};

// 1. 產生靜態語系路由 (GitHub Pages 必備)
export function generateStaticParams() {
  return [{ locale: "en" }, { locale: "zh-TW" }, { locale: "ja" }];
}

// 2. Next.js 15 中，params 變成 Promise，必須使用 await 解析
export default async function LocaleLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;

  // 3. 動態載入對應語系的字典檔
  let messages;
  try {
    messages = (await import(`../../messages/${locale}.json`)).default;
  } catch (error) {
    notFound();
  }

  return (
    // 4. 將字型變數與 lang 屬性掛在最外層 HTML
    <html
      lang={locale}
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/* 5. 用 Provider 包覆整個網頁內容，讓底下元件都能使用翻譯 */}
        <NextIntlClientProvider locale={locale} messages={messages}>
          {children}
        </NextIntlClientProvider>
      </body>
    </html>
  );
}